"""Builds lambda/lambda_function.py = solution/checks.py + lambda/handler_part.py
(one single file that learners paste into the Lambda Console editor).
Run after changing checks:  python scripts/build_lambda.py"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
checks = (root / "solution" / "checks.py").read_text()
handler = (root / "lambda" / "handler_part.py").read_text()
header = ('# CloudAdhar Cloud Guardian - AWS Lambda function\n'
          '# Paste this WHOLE file into the Lambda Console code editor (lambda_function.py), then click Deploy.\n'
          '# Generated by scripts/build_lambda.py - edit solution/checks.py or lambda/handler_part.py instead.\n\n')
(root / "lambda" / "lambda_function.py").write_text(header + checks + handler)
print("Built lambda/lambda_function.py")
